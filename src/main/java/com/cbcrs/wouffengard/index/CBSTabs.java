package com.cbcrs.wouffengard.index;

import com.cbcrs.wouffengard.CBSReference;
import com.cbcrs.wouffengard.TheRoarOfSteel;
import com.cbcrs.wouffengard.TheRoarOfSteelRegistrate;
import net.minecraft.core.registries.Registries;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.item.CreativeModeTab;
import net.minecraft.world.item.ItemStack;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;

import java.util.function.Supplier;

/**
 * The mod's dedicated creative tab.
 *
 * <p>Follows the pattern Create Big Cannons itself uses: register the tab with
 * a plain {@link DeferredRegister}, then point registrate at the tab key via
 * {@code defaultCreativeTab}, so every registrate-registered item added in
 * later phases appears in this tab without per-item wiring.
 */
public final class CBSTabs {

    private CBSTabs() {
    }

    public static final DeferredRegister<CreativeModeTab> TABS =
            DeferredRegister.create(Registries.CREATIVE_MODE_TAB, TheRoarOfSteel.MOD_ID);

    /** Lang key for the tab title; provided in both locale files. */
    public static final String MAIN_TAB_LANG_KEY = "itemGroup.cbc_rs";

    public static final ResourceKey<CreativeModeTab> MAIN_TAB_KEY =
            ResourceKey.create(Registries.CREATIVE_MODE_TAB, CBSReference.loc("main"));

    public static final DeferredHolder<CreativeModeTab, CreativeModeTab> MAIN_TAB =
            TABS.register("main", CBSTabs::buildMainTab);

    public static void register(IEventBus modEventBus) {
        TABS.register(modEventBus);
        // Route every registrate-registered item into our own tab. This must run
        // BEFORE any content is registered, otherwise the items are created
        // while no default tab is set and never get bound to one.
        TheRoarOfSteelRegistrate.get().defaultCreativeTab(MAIN_TAB_KEY);
        // en_us is generated by Registrate's lang provider, so the keys that are
        // not attached to an item must be injected here. zh_cn is maintained by
        // hand in assets/cbc_rs/lang/zh_cn.json.
        TheRoarOfSteelRegistrate.get().addRawLang(MAIN_TAB_LANG_KEY, "Create Big Cannons: The Roar of Steel");
        TheRoarOfSteelRegistrate.get().addRawLang("cbc_rs.tooltip.caliber.small", "Small Caliber");
        TheRoarOfSteelRegistrate.get().addRawLang("cbc_rs.tooltip.caliber.medium", "Medium Caliber");
        TheRoarOfSteelRegistrate.get().addRawLang("cbc_rs.tooltip.caliber.large", "Large Caliber");
        TheRoarOfSteelRegistrate.get().addRawLang("cbc_rs.tooltip.spread_reducer",
                "Reduces spread only; does not affect chamber pressure.");
    }

    /**
     * Every item declared through registrate is inserted here.
     *
     * <p>Kept explicit (rather than relying purely on the registrate tab
     * binding) so the tab's contents are obvious from the source. The order
     * below mirrors the processing chain, which makes the tab readable:
     * ores, then raw ore, then crushed ore, then the metal items.
     */
    private static void addItems(CreativeModeTab.ItemDisplayParameters parameters,
                                 CreativeModeTab.Output output) {
        // Ores
        output.accept(CBSOres.SCHEELITE_ORE);
        output.accept(CBSOres.WOLFRAMITE_ORE);

        // Raw ore drops
        output.accept(CBSMaterials.RAW_SCHEELITE);
        output.accept(CBSMaterials.RAW_WOLFRAMITE);

        // Crushing products
        output.accept(CBSMaterials.CRUSHED_RAW_SCHEELITE);
        output.accept(CBSMaterials.CRUSHED_RAW_WOLFRAMITE);

        // Metal
        output.accept(CBSItems.TUNGSTEN_INGOT);
        output.accept(CBSMaterials.TUNGSTEN_NUGGET);
    }

    private static CreativeModeTab buildMainTab() {
        return CreativeModeTab.builder()
                .title(Component.translatable(MAIN_TAB_LANG_KEY))
                // Phase 1: the tungsten ingot is the mod's first item, so it also
                // serves as the tab icon.
                .icon(() -> CBSItems.TUNGSTEN_INGOT.asStack())
                .displayItems(CBSTabs::addItems)
                .build();
    }

    /** The tab as a supplier, for later phases that need one. */
    public static Supplier<CreativeModeTab> mainTabSupplier() {
        return MAIN_TAB;
    }
}
